"""backtest: publishes the committed results of r1.py (the harness) as dashboard records. It does not fetch anything.
The results file is regenerated by running r1.py (it needs network, so it is not part of the refresh); its own generated_at
is the record time, so the page shows how old the test is. Everything is SIMULATED."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = {"XAUT": "XAUTUSDT", "BNB": "BNBUSDT", "ETH": "ETHUSDT", "SOL": "SOLUSDT"}

def build(res):
    recs = []
    for c, s in NAMES.items():
        r = res["symbols"][s]
        recs.append({"id": "backtest.%susdt" % c.lower(), "title_ar": "الاختبار الرجعي %s (محاكاة)" % c, "unit": "backtest",
                     "value": {"strategies": r["strategies"], "names": res["strategies"]},
                     "stats": {"candles": r["candles"], "from": r["from"], "to": r["to"], "split": res["split"], "fee_per_side": res["fee_per_side"],
                               "slippage_per_side": res["slippage_per_side"], "exit_grid": res["exit_grid"], "stop_rule": res["stop_rule"]},
                     "source": {"name": "Binance public klines backtest (run by this repo)", "url": "https://data-api.binance.vision/api/v3/klines"},
                     "fetched_at": res["generated_at"], "label": "simulated", "max_age_hours": 720, "checked_against": None})
    return {"meta": {"module": "backtest", "version": "1.0.0"}, "records": recs}

def main():
    with open(os.path.join(HERE, "results.json"), encoding="utf-8") as f: res = json.load(f)
    with open(os.path.join(os.environ["OUT_DIR"], "backtest.json"), "w", encoding="utf-8") as f:
        json.dump(build(res), f, ensure_ascii=False, separators=(",", ":"))

if __name__ == "__main__":
    main()
