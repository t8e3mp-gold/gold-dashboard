export function History({ sym, name }: { sym: string; name: string }) {
    const d = H[sym];
    const c = d.map(r => r[4]);
    const last = c[c.length - 1];
    const ch = (n: number) => d.length > n ? `${((last / c[c.length - 1 - n] - 1) * 100).toFixed(1)} بالمئة` : 'غير متاح';
    const hi = Math.max(...d.map(r => r[2])), lo = Math.min(...d.map(r => r[3]));
    const hiT = d.find(r => r[2] === hi)![0], loT = d.find(r => r[3] === lo)![0];
    const best = d.reduce((a, r) => (r[4] / r[1] > a[4] / a[1] ? r : a));
    const worst = d.reduce((a, r) => (r[4] / r[1] < a[4] / a[1] ? r : a));
    const dr = (r: number[]) => `${((r[4] / r[1] - 1) * 100).toFixed(1)} بالمئة`;
    return <Group label={`ذاكرة ${name}: التاريخ المحفوظ`} heading>
        <LineChart label={`الإغلاق اليومي، ${d.length} يوم من ${day(d[0][0])}`} xName="اليوم" data={d.map((r, i) => ({ x: i, label: day(r[0]), value: r[4], valueLabel: f(r[4]) }))} />
        <Facts items={[
            { label: 'عدد الأيام المحفوظة', value: `${d.length} يوم` },
            { label: 'التغير 7 أيام', value: ch(7) }, { label: 'التغير 30 يوم', value: ch(30) },
            { label: 'التغير 90 يوم', value: ch(90) }, { label: 'التغير 180 يوم', value: ch(180) },
            { label: 'أعلى سعر في الفترة', value: `${f(hi)} (${day(hiT)})` },
            { label: 'أدنى سعر في الفترة', value: `${f(lo)} (${day(loT)})` },
            { label: 'البعد عن القمة', value: `${((last / hi - 1) * 100).toFixed(1)} بالمئة` },
            { label: 'أفضل يوم', value: `${dr(best)} (${day(best[0])})` },
            { label: 'أسوأ يوم', value: `${dr(worst)} (${day(worst[0])})` },
        ]} />
        {sym === 'XAUTUSDT' && <Callout title="تنبيه عن عمر البيانات" tone="note">توكن XAUT على بينانس سبوت له تاريخ {d.length} يوم فقط، لذلك لا توجد سنة كاملة.</Callout>}
        <Caption>آخر حفظ للتاريخ {new Date(SAVED).toLocaleString('ar-EG')}. شموع يومية مكتملة فقط من بينانس سبوت.</Caption>
    </Group>;
}

